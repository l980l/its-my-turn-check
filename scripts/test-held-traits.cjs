const assert=require('node:assert/strict');
const {createGameHarness}=require('./game-harness.cjs');
const h=createGameHarness({withHeldUi:true});
h.reset();
const {S,ui}=h.game;
assert.equal(ui.heldSlots.length,6);
assert.ok(ui.heldSlots.every(button=>button.disabled));
S.player.traits=['shockwave','royalVector','prismaticImpact','astralCrown'];
S.player.materials=['fork','echoBlade'];
h.game.playerMove({x:1,y:0});
assert.equal(ui.heldSlots.filter(button=>!button.disabled).length,4,'only equipped traits appear, not bag materials');
assert.deepEqual(Array.from(ui.heldSlots.slice(0,4),button=>button.dataset.tier),['1','2','3','4']);
const before=JSON.stringify({phase:S.phase,score:S.score,xp:S.player.xp,traits:S.player.traits});
ui.heldSlots[1].handlers.click();
assert.equal(ui.heldName.textContent,'ROYAL VECTOR');
assert.equal(S.heldTraitIndex,1);
assert.equal(ui.heldSlots[1].attributes['aria-expanded'],'true');
assert.equal(JSON.stringify({phase:S.phase,score:S.score,xp:S.player.xp,traits:S.player.traits}),before,'inspecting traits does not move or spend a turn');
ui.heldSlots[1].handlers.click();
assert.equal(S.heldTraitIndex,null);
ui.heldSlots[3].handlers.click();
assert.equal(ui.heldDetails.dataset.tier,'4');
ui.heldClose.handlers.click();
assert.equal(S.heldTraitIndex,null);
ui.heldSlots[5].handlers.click();
assert.equal(S.heldTraitIndex,null,'empty slots cannot open stale details');
S.player.rank=2;
h.game.openUpgrade(true);
const reward=S.upgradeOptions[0].id;
ui.heldSlots[0].handlers.click();
h.game.chooseUpgrade(0);
assert.equal(ui.heldSlots.filter(button=>!button.disabled).length,5);
assert.equal(ui.heldSlots[4].title,require('../traits.js').byId[reward].name);
assert.equal(S.heldTraitIndex,null,'equipment changes clear the previous description');
h.game.reset();
assert.ok(ui.heldSlots.every(button=>button.disabled));
assert.ok(ui.heldSlots.every(button=>button.innerHTML===''));
console.log('held trait HUD tests passed: six slots, tier colors, bag exclusion, inspection, reward refresh and reset');
